#!/usr/bin/env python3
import sys, os, json, base64, io
from PIL import Image
from samsungtvws import SamsungTVWS

if len(sys.argv) < 2:
    print("Usage: python3 sync_thumbs.py <TV_IP_ADDRESS>")
    sys.exit(1)

tv_ip = sys.argv[1]
token_file = os.path.join(os.path.dirname(__file__), "tv-token.txt")

print(f"Connecting to Frame TV at {tv_ip}...")
print("(If prompted on your TV screen, press 'Allow' on your remote)")
tv = SamsungTVWS(host=tv_ip, port=8002, token_file=token_file)
art = tv.art()

# Fetch list of user-uploaded photos (Category MY-C0002)
available = art.available('MY-C0002')
content_ids = [
    item['content_id'] for item in available
    if 'content_id' in item and item['content_id'].startswith('MY')
]

print(f"Found {len(content_ids)} custom photos on the TV. Downloading thumbnails...")

# Load any previously cached thumbnails so we only download missing ones
cache_js_path = os.path.join(os.path.dirname(__file__), "thumbs_cache.js")
thumbs = {}

for cid in content_ids:
    try:
        raw_bytes = None
        # Try modern 2022-2026 Frame API (get_thumbnail_list) first, then fallback
        try:
            res = art.get_thumbnail_list([cid])
            if isinstance(res, dict) and res:
                raw_bytes = list(res.values())[0]
            elif isinstance(res, (bytes, bytearray)):
                raw_bytes = res
        except Exception:
            raw_bytes = art.get_thumbnail(cid)

        if raw_bytes:
            # Resize & compress to a lightweight 16:9 JPEG data URL for the browser
            img = Image.open(io.BytesIO(raw_bytes)).convert("RGB")
            img.thumbnail((320, 180))
            buf = io.BytesIO()
            img.save(buf, format="JPEG", quality=80)
            b64 = base64.b64encode(buf.getvalue()).decode("ascii")
            thumbs[cid] = f"data:image/jpeg;base64,{b64}"
            print(f"  ✔ Pulled {cid}")
        else:
            print(f"  ⚠ Empty thumbnail returned for {cid}")
    except Exception as e:
        print(f"  ✗ Failed {cid}: {e}")

# Write out thumbs_cache.js so frame-art-manager.html loads them automatically
with open(cache_js_path, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by sync_thumbs.py\n")
    f.write("window.FAM_PRELOADED_THUMBS = " + json.dumps(thumbs) + ";\n")
    f.write("""
(function() {
  if (window.FAM_PRELOADED_THUMBS) {
    for (const [cid, dataUrl] of Object.entries(window.FAM_PRELOADED_THUMBS)) {
      try { localStorage.setItem('fam_thumb_' + cid, dataUrl); } catch (e) {}
    }
    console.log('✔ Loaded ' + Object.keys(window.FAM_PRELOADED_THUMBS).length + ' TV thumbnails into cache.');
  }
})();
""")

print(f"\n✔ Done! Saved {len(thumbs)} thumbnails to thumbs_cache.js.")
print("Refresh frame-art-manager.html in your browser to see all your previews!")
